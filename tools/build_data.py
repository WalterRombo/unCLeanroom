"""Regenerate js/locations.js and js/floorplan.js.

Usage (from the repo root):
    pip install openpyxl
    python tools/build_data.py [path/to/Locations & Risk Assessment.xlsx]

Reads the 'Generated Locations' tab (C grid ref, D grade, E location/equipment,
F agar, G test type, H full description) and embeds assets/floorplan.png
so the site works without any server-side files.
"""
import base64, json, sys, pathlib
import openpyxl

root = pathlib.Path(__file__).resolve().parent.parent
xlsx = sys.argv[1] if len(sys.argv) > 1 else root / "data" / "Locations___Risk_Assessment_2026.xlsx"
ws = openpyxl.load_workbook(xlsx, data_only=True)["Generated Locations"]

rows = []
for r in ws.iter_rows(min_row=4, values_only=True):
    if r[2] and r[7]:  # grid ref + description present
        rows.append([str(r[7]).strip(), str(r[2]).strip(), str(r[4] or "").strip(),
                     str(r[5] or "").strip(), str(r[6] or "").strip(), str(r[3] or "").strip()])

(root / "js" / "locations.js").write_text(
    "// Generated by tools/build_data.py - [name, grid, equipment, agar, test type, grade]\n"
    "window.LOCATIONS = " + json.dumps(rows, separators=(",", ":")) + ";\n", encoding="utf-8")
b64 = base64.b64encode((root / "assets" / "floorplan.png").read_bytes()).decode()
(root / "js" / "floorplan.js").write_text(f'window.FLOORPLAN = "data:image/png;base64,{b64}";\n')
print(len(rows), "locations written")
